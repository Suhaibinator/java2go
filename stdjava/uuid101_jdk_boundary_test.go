func TestUUID101CallerExecutionNaturalComparison(t *testing.T) {
	execution := NewExecution()
	a := NewJavaUUID(-1, 0)
	b := NewJavaUUID(1, 0)
	var companion interface {
		CompareToJava2goExecution(*Execution, *JavaUUID) int32
	} = a
	if companion.CompareToJava2goExecution(execution, b) != -1 || ComparableCompareToExecution(execution, a, b) != -1 || !ObjectEqualsExecution(execution, a, NewJavaUUID(-1, 0)) {
		t.Fatal("caller execution/value dispatch bridge")
	}
}
